"""Self-contained HTML evidence pack for one alert, with a SHA-256 integrity hash and a method statement."""
from __future__ import annotations

import hashlib
import html
import json

METHOD = ("Generated by DarkLens. Category comes from a hybrid of detection rules and a TF-IDF classifier; "
          "the score combines signals with noisy-OR after discounting generic content signals. "
          "Results are heuristics to prioritise human review, not proof of wrongdoing.")


def build_pack(alert: dict) -> tuple[str, str]:
    """Return (html, sha256-of-canonical-json). The hash covers the alert data so tampering is detectable."""
    canon = json.dumps(alert, sort_keys=True, ensure_ascii=False)
    digest = hashlib.sha256(canon.encode("utf-8")).hexdigest()
    rows = "".join(
        f"<tr><td>{html.escape(s['name'])}</td><td>{s['score']}</td><td>{html.escape(s['why'])}</td>"
        f"<td><code>{html.escape(s.get('evidence', ''))}</code></td></tr>" for s in alert.get("signals", [])
    )
    iocs = "".join(f"<li><b>{html.escape(t)}</b>: <code>{html.escape(v)}</code></li>"
                   for t, vs in (alert.get("iocs") or {}).items() for v in vs)
    page = f"""<!doctype html><meta charset=utf-8><title>DarkLens evidence pack</title>
<style>body{{font:15px system-ui;max-width:860px;margin:2rem auto;padding:0 1rem;color:#1a1a1a}}
table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #ccc;padding:6px;text-align:left;vertical-align:top}}
.sev{{display:inline-block;padding:2px 10px;border-radius:12px;background:#222;color:#fff}}code{{word-break:break-all}}</style>
<h1>Evidence pack</h1>
<p><span class=sev>{html.escape(str(alert.get('severity', '')))}</span> score {alert.get('score')} / 100 &middot; {html.escape(str(alert.get('category', '')))}</p>
<h2>{html.escape(alert.get('title', ''))}</h2>
<p>Source: {html.escape(alert.get('source', ''))} &middot; seen {html.escape(str(alert.get('seen_at', '')))}</p>
<blockquote>{html.escape((alert.get('text') or '')[:600])}</blockquote>
<h3>Why this scored {alert.get('score')}</h3>
<table><tr><th>Signal</th><th>Strength</th><th>Why</th><th>Evidence</th></tr>{rows}</table>
<h3>Indicators</h3><ul>{iocs or '<li>none</li>'}</ul>
<h3>Method</h3><p>{html.escape(METHOD)}</p>
<h3>Integrity</h3><p>SHA-256 of alert data: <code>{digest}</code></p>"""
    return page, digest
